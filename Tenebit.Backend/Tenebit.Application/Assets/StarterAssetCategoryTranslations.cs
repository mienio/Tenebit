        new Dictionary<string, IReadOnlyDictionary<string, (string Name, string Description)>>
        {
            ["en"] = EnglishByPolishName,
            ["es"] = SpanishByPolishName,
            ["de"] = GermanByPolishName,
            ["it"] = ItalianByPolishName,
            ["fr"] = FrenchByPolishName
        };

    public static string TranslateName(bool isSystem, string language, string name)
    {
        if (isSystem && ByLanguage.TryGetValue(language, out var dict) && dict.TryGetValue(name, out var translation))
        {
            return translation.Name;
        }

        return name;
    }

    public static string TranslateDescription(bool isSystem, string language, string polishName, string description)
    {
        if (isSystem && ByLanguage.TryGetValue(language, out var dict) && dict.TryGetValue(polishName, out var translation))
        {
            return translation.Description;
        }

        return description;
    }
